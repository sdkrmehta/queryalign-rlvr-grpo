        "            # Point 3 (P0): Proper handling of empty ground truth\n",
        "            is_empty = bool(gold_is_empty[i]) if (gold_is_empty and i < len(gold_is_empty)) else (len(gold_rows) == 0)\n",
        "            if is_empty:\n",
        "                # If gold query produces 0 rows, candidate must also produce 0 rows\n",
        "                # AND candidate must parse to a non-empty SELECT query (anti-trivial check)\n",
        "                if len(cand_rows) == 0 and len(sql) > 10:\n",
        "                    rewards.append(1.00)\n",
        "                else:\n",
        "                    rewards.append(0.00)\n",
        "            else:\n",
        "                # Multiset equivalence check (order-agnostic, duplicate-preserving)\n",
        "                if Counter(cand_rows) == Counter(gold_rows):\n",
        "                    rewards.append(1.00)\n",
        "                else:\n",
        "                    rewards.append(0.00)\n",
        "        except Exception:\n",
        "            rewards.append(0.00)\n",
        "    return rewards\n",
        "\n",
