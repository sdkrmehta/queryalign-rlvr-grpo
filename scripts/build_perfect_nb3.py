        "    for i, c in enumerate(completions):\n",
        "        text = extract_completion_text(c)\n",
        "        sql, ok = parse_sql(text)\n",
        "        target_db = db_id[i] if (db_id and i < len(db_id)) else \"\"\n",
        "        if not ok or not target_db or not gold_result_json or i >= len(gold_result_json):\n",
        "            rewards.append(0.00)\n",
        "            continue\n",
        "        db_file = DATA_DIR / \"raw\" / \"spider\" / \"database\" / target_db / f\"{target_db}.sqlite\"\n",
        "        if not db_file.exists():\n",
        "            rewards.append(0.00)\n",
        "            continue\n",
        "        # Point 2 & 4 (P0): Uses execute_sandbox_query with defined uri and genuine timeout\n",
        "        success, cand_rows, trunc, err = execute_sandbox_query(db_file, sql, timeout_sec=2.0)\n",
        "        if not success or trunc or cand_rows is None:\n",
        "            rewards.append(0.00)\n",
        "            continue\n",
        "        try:\n",
        "            gold_raw = json.loads(gold_result_json[i])\n",
