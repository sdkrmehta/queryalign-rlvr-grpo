        "                continue\n",
        "            # Enforce schema whitelist\n",
        "            if valid_tables and i < len(valid_tables) and valid_tables[i]:\n",
        "                allowed = {str(tbl).lower() for tbl in valid_tables[i]}\n",
        "                if referenced_tables and (referenced_tables - allowed):\n",
