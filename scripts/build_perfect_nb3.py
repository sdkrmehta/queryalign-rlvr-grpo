        "\n",
        "# ── Point 1 (P0): Conversational Completion Extractor ──────────────────────\n",
        "def extract_completion_text(c: Any) -> str:\n",
        "    \"\"\"\n",
        "    Robustly extract the raw text generated by the assistant, whether TRL passes:\n",
        "    - A plain string\n",
        "    - A dictionary {'role': 'assistant', 'content': '...'}\n",
        "    - A list of messages [{'role': 'user', ...}, {'role': 'assistant', 'content': '...'}]\n",
        "    \"\"\"\n",
        "    if isinstance(c, str):\n",
        "        return c\n",
        "    if isinstance(c, list):\n",
        "        for msg in reversed(c):\n",
        "            if isinstance(msg, dict) and msg.get(\"role\") == \"assistant\":\n",
        "                return msg.get(\"content\", \"\")\n",
        "            if isinstance(msg, dict) and \"content\" in msg:\n",
        "                return msg.get(\"content\", \"\")\n",
        "        if len(c) > 0 and isinstance(c[-1], str):\n",
        "            return c[-1]\n",
        "        return str(c)\n",
        "    if isinstance(c, dict):\n",
        "        return c.get(\"content\", str(c))\n",
        "    return str(c)\n",
        "\n",
        "def parse_sql(text: str) -> Tuple[Optional[str], bool]:\n",
        "    \"\"\"Strictly extract SQL enclosed in <sql>...</sql> tags with no trailing text.\"\"\"\n",
        "    if not text or \"<sql>\" not in text or \"</sql>\" not in text:\n",
        "        return None, False\n",
        "    if text.count(\"<sql>\") != 1 or text.count(\"</sql>\") != 1:\n",
        "        return None, False\n",
        "    idx1 = text.find(\"<sql>\") + len(\"<sql>\")\n",
        "    idx2 = text.find(\"</sql>\")\n",
        "    if idx1 > idx2:\n",
        "        return None, False\n",
        "    trailing = text[idx2 + len(\"</sql>\"):].strip()\n",
        "    if trailing:\n",
        "        return None, False  # Disallowed trailing text after closing tag\n",
        "    sql = text[idx1:idx2].strip()\n",
        "    return (sql, True) if sql else (None, False)\n",
        "\n",
        "# ── Point 4 (P0): Strict Read-Only Sandbox Authorizer & Genuine Timeout ───\n",
        "SAFE_FUNCTIONS = {\"count\", \"sum\", \"avg\", \"min\", \"max\", \"lower\", \"upper\", \"length\", \"substr\", \"round\", \"abs\", \"coalesce\", \"strftime\", \"date\"}\n",
        "\n",
        "def create_authorizer():\n",
        "    def callback(action, arg1, arg2, db, trigger):\n",
        "        if action == sqlite3.SQLITE_SELECT:\n",
        "            return sqlite3.SQLITE_OK\n",
        "        if action == sqlite3.SQLITE_READ:\n",
        "            if (arg1 or \"\").lower() in {\"sqlite_master\", \"sqlite_schema\", \"sqlite_temp_master\"}:\n",
        "                return sqlite3.SQLITE_DENY\n",
        "            return sqlite3.SQLITE_OK\n",
        "        if action == sqlite3.SQLITE_FUNCTION:\n",
        "            if (arg2 or \"\").lower() in SAFE_FUNCTIONS:\n",
        "                return sqlite3.SQLITE_OK\n",
        "            return sqlite3.SQLITE_DENY\n",
        "        return sqlite3.SQLITE_DENY\n",
        "    return callback\n",
        "\n",
        "def execute_sandbox_query(db_path: Path, sql: str, timeout_sec: float = 2.0) -> Tuple[bool, Optional[List[Tuple]], bool, Optional[str]]:\n",
        "    \"\"\"\n",
        "    Executes SQL query against SQLite database with:\n",
        "    - Strict read-only mode\n",
        "    - SQLite authorizer blocking catalog & dangerous functions\n",
        "    - Progress handler enforcing a genuine wall-clock deadline\n",
        "    - Truncation limit of 5,000 rows to prevent OOM\n",
        "    \"\"\"\n",
        "    start = time.perf_counter()\n",
        "    deadline = start + timeout_sec\n",
        "    uri = f\"file:{db_path.resolve().as_posix()}?mode=ro\"\n",
        "    conn = None\n",
        "    try:\n",
        "        conn = sqlite3.connect(uri, uri=True, timeout=1.0)\n",
        "        conn.execute(\"PRAGMA query_only = ON\")\n",
        "        conn.set_authorizer(create_authorizer())\n",
        "        conn.set_progress_handler(lambda: 1 if time.perf_counter() > deadline else 0, 10000)\n",
        "        cur = conn.cursor()\n",
        "        cur.execute(sql)\n",
        "        rows = cur.fetchmany(5001)\n",
        "        if len(rows) > 5000:\n",
        "            return False, None, True, \"RESULT_TRUNCATED\"\n",
        "        return True, rows, False, None\n",
        "    except Exception as e:\n",
        "        return False, None, False, str(e)\n",
        "    finally:\n",
        "        if conn:\n",
        "            try:\n",
        "                conn.close()\n",
        "            except Exception:\n",
        "                pass\n",
        "\n",
        "# ── Reward 1: Format Reward (+0.20 or -0.50) ──────────────────────────────\n",
        "def reward_format(completions, **kwargs):\n",
        "    rewards = []\n",
        "    for c in completions:\n",
        "        text = extract_completion_text(c)\n",
        "        sql, ok = parse_sql(text)\n",
        "        rewards.append(0.20 if ok else -0.50)\n",
        "    return rewards\n",
        "\n",
        "# ── Reward 2: AST & Schema Validation (+0.20 or 0.00) (Point 7 - P1) ──────\n",
        "def reward_ast_schema(completions, valid_tables=None, **kwargs):\n",
        "    rewards = []\n",
        "    for i, c in enumerate(completions):\n",
        "        text = extract_completion_text(c)\n",
        "        sql, ok = parse_sql(text)\n",
        "        if not ok or not sql:\n",
        "            rewards.append(0.00)\n",
        "            continue\n",
        "        try:\n",
        "            stmts = sqlglot.parse(sql, read=\"sqlite\")\n",
        "            if not stmts or len(stmts) != 1 or not isinstance(stmts[0], (exp.Select, exp.Union, exp.Intersect, exp.Except)):\n",
        "                rewards.append(0.00)\n",
        "                continue\n",
        "            ast = stmts[0]\n",
        "            # Extract CTE aliases so they are not mistaken for external tables\n",
        "            cte_names = set()\n",
        "            for cte in ast.find_all(exp.CTE):\n",
        "                if cte.alias:\n",
        "                    cte_names.add(cte.alias.lower())\n",
        "            # Extract all table identifiers\n",
        "            raw_tables = {t.name.lower() for t in ast.find_all(exp.Table) if t.name}\n",
        "            referenced_tables = raw_tables - cte_names\n",
        "            # Reject catalog queries\n",
        "            if referenced_tables & {\"sqlite_master\", \"sqlite_schema\", \"sqlite_temp_master\"}:\n",
